// Checks the built site in dist/. Run after `npm run build` (npm run test:dist does both in CI).
import { test } from 'node:test';
import assert from 'node:assert/strict';
import { existsSync, readFileSync, readdirSync, statSync } from 'node:fs';
import { join, relative } from 'node:path';

const DIST = new URL('../dist/', import.meta.url).pathname;
const SITE = 'https://adityaaswani.com';
const built = existsSync(join(DIST, 'index.html'));
const opts = built ? {} : { skip: 'dist/ not built; run npm run build first' };

function htmlFiles(dir = DIST) {
  const out = [];
  for (const name of readdirSync(dir)) {
    const p = join(dir, name);
    if (statSync(p).isDirectory()) out.push(...htmlFiles(p));
    else if (name.endsWith('.html')) out.push(p);
  }
  return out;
}

const pages = built ? htmlFiles().map((file) => ({ file, rel: relative(DIST, file), html: readFileSync(file, 'utf8') })) : [];
// The /zoom redirect page is generated by Astro and only holds a meta refresh to Zoom.
const contentPages = pages.filter((p) => p.rel !== 'zoom/index.html');

const decode = (s) => s.replace(/&amp;/g, '&').replace(/&#38;/g, '&');

// Internal URL → path, or null when the URL is external / not a page or asset reference.
function internalPath(raw) {
  const url = decode(raw.trim());
  if (!url || url.startsWith('#') || url.startsWith('//') || /^(mailto|tel|data|javascript):/i.test(url)) return null;
  if (url.startsWith('/')) return new URL(url, SITE).pathname;
  if (url.startsWith(SITE + '/') || url === SITE) return new URL(url).pathname;
  return null;
}

// What the static host serves for a path: a file, a directory index, or nothing.
function resolve(path) {
  const p = decodeURIComponent(path);
  if (p.endsWith('/')) return existsSync(join(DIST, p, 'index.html')) ? 'ok' : 'missing';
  if (existsSync(join(DIST, p)) && statSync(join(DIST, p)).isFile()) return 'ok';
  if (existsSync(join(DIST, p, 'index.html'))) return 'redirect'; // GitHub Pages 301s /x to /x/
  return 'missing';
}

function refs(html) {
  const out = [];
  for (const m of html.matchAll(/\s(href|src)="([^"]*)"/g)) out.push({ attr: m[1], url: m[2] });
  for (const m of html.matchAll(/\ssrcset="([^"]*)"/g)) {
    for (const part of m[1].split(',')) out.push({ attr: 'srcset', url: part.trim().split(/\s+/)[0] });
  }
  return out;
}

test('every og:image is absolute and resolves to a file in dist', opts, () => {
  for (const { rel, html } of contentPages) {
    const imgs = [...html.matchAll(/<meta property="og:image" content="([^"]+)"/g)].map((m) => m[1]);
    // Pages built on Layout always carry one; the standalone /preview* design pages have none.
    if (html.includes('rel="canonical"')) assert.ok(imgs.length >= 1, `${rel}: no og:image`);
    for (const img of imgs) {
      assert.ok(img.startsWith(SITE + '/'), `${rel}: og:image ${img} is not on ${SITE}`);
      assert.equal(resolve(new URL(img).pathname), 'ok', `${rel}: og:image ${img} is not in dist`);
    }
  }
});

test('the default share image is 1200x630 and under 300 KB, and no page shares the original photo', opts, () => {
  const buf = readFileSync(join(DIST, 'og-default.jpg'));
  assert.ok(buf.length < 300 * 1024, `og-default.jpg is ${buf.length} bytes`);
  // Find the SOF0/SOF2 marker for the JPEG's pixel size.
  let i = 2, size = null;
  while (i < buf.length) {
    const marker = buf[i + 1];
    const len = buf.readUInt16BE(i + 2);
    if (marker === 0xc0 || marker === 0xc2) { size = [buf.readUInt16BE(i + 7), buf.readUInt16BE(i + 5)]; break; }
    i += 2 + len;
  }
  assert.deepEqual(size, [1200, 630]);
  for (const { rel, html } of pages) assert.ok(!html.includes('aditya-photo-new.jpg'), `${rel} references the 13.5 MB original`);
});

test('every internal href/src/srcset maps to a file in dist, with no trailing-slash redirect', opts, () => {
  const problems = [];
  for (const { rel, html } of contentPages) {
    for (const { attr, url } of refs(html)) {
      const path = internalPath(url);
      if (path === null) continue;
      const r = resolve(path);
      if (r !== 'ok') problems.push(`${rel}: ${attr}="${url}" → ${r}`);
    }
  }
  assert.deepEqual(problems, []);
});

test('no internal link lacks its trailing slash', opts, () => {
  const problems = [];
  for (const { rel, html } of contentPages) {
    for (const m of html.matchAll(/<a\s[^>]*href="([^"]*)"/g)) {
      const path = internalPath(m[1]);
      if (path === null) continue;
      const last = path.split('/').pop();
      if (last !== '' && !last.includes('.')) problems.push(`${rel}: ${m[1]}`);
    }
  }
  assert.deepEqual(problems, []);
});

test('the sitemap lists only the public pages and no /preview page', opts, () => {
  const xml = readFileSync(join(DIST, 'sitemap-0.xml'), 'utf8');
  const locs = [...xml.matchAll(/<loc>([^<]+)<\/loc>/g)].map((m) => m[1]).sort();
  assert.ok(!xml.includes('/preview'), 'sitemap lists a /preview page');
  assert.deepEqual(locs, ['/', '/contact/', '/learn-meditation/', '/links/', '/support/'].map((p) => SITE + p).sort());
});

test('robots.txt allows all and points at the sitemap', opts, () => {
  const txt = readFileSync(join(DIST, 'robots.txt'), 'utf8');
  assert.match(txt, /^User-agent: \*$/m);
  assert.match(txt, /^Allow: \/$/m);
  assert.match(txt, /^Sitemap: https:\/\/adityaaswani\.com\/sitemap-index\.xml$/m);
});

test('the home page has valid Person JSON-LD', opts, () => {
  const html = readFileSync(join(DIST, 'index.html'), 'utf8');
  const blocks = [...html.matchAll(/<script type="application\/ld\+json">([\s\S]*?)<\/script>/g)];
  assert.equal(blocks.length, 1);
  const data = JSON.parse(blocks[0][1]);
  assert.equal(data['@context'], 'https://schema.org');
  assert.equal(data['@type'], 'Person');
  assert.equal(data.name, 'Aditya Aswani');
  assert.equal(data.url, SITE + '/');
  assert.equal(resolve(new URL(data.image).pathname), 'ok');
  assert.ok(typeof data.description === 'string' && data.description.length > 10);
  assert.ok(Array.isArray(data.sameAs) && data.sameAs.length > 0);
  for (const u of data.sameAs) assert.equal(new URL(u).protocol, 'https:');
  assert.ok(blocks[0].index < html.indexOf('</head>'), 'JSON-LD should sit in <head>');
});

test('every page in dist sends strict-origin-when-cross-origin as its referrer policy', opts, () => {
  for (const { rel, html } of pages) {
    const metas = html.match(/<meta name="referrer" content="[^"]*">/g) || [];
    assert.deepEqual(metas, ['<meta name="referrer" content="strict-origin-when-cross-origin">'], rel);
  }
});
